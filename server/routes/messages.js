// POST /messages/cleanup-system-notifs
// One-time admin endpoint: deletes all legacy system-generated notification messages
// (e.g. "New Quiz assigned: ...", "New Assignment assigned: ...") from the messages table.
// These were replaced by fetching directly from the assignments table.
router.post('/cleanup-system-notifs', async (req, res) => {
  try {
    const adminKey = (req.body?.adminKey || req.query.adminKey || '').trim();
    if (adminKey !== 'aivorah-admin-2026') {
      return res.status(403).json({ error: 'Forbidden' });
    }

    // Fetch and delete in batches using LIKE filters for each prefix
    let totalDeleted = 0;
    const prefixes = [
      'New Quiz assigned:',
      'New Assignment assigned:',
      'New Challenge assigned:',
    ];

    for (const prefix of prefixes) {
      const { data: rows, error: fetchErr } = await supabase
        .from('messages')
        .select('id')
        .like('content', `${prefix}%`)
        .limit(1000);

      if (fetchErr) return res.status(500).json({ error: fetchErr.message, prefix });

      const ids = (rows || []).map(r => r.id);
      if (ids.length === 0) continue;

      const { error: delErr } = await supabase
        .from('messages')
        .delete()
        .in('id', ids);

      if (delErr) return res.status(500).json({ error: delErr.message, prefix });
      totalDeleted += ids.length;
    }

    res.json({ ok: true, deleted: totalDeleted });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

